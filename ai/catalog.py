"""Database side of the data catalog.

    python -m ai.catalog sync       copy ai/metadata.yaml into meta_tables / meta_columns
    python -m ai.catalog profile    refresh live column stats and record drift
    python -m ai.catalog drift      list open drift alerts

ai/metadata.yaml stays the source of truth for meanings and security rules (reviewed in
git). The database gets:
  - meta_tables, meta_columns   a read-only copy of the YAML (regenerated by `sync`)
  - meta_column_stats           live facts per column: counts, nulls, distinct values,
                                ranges, and the values actually present
  - meta_drift                  open alerts when the data or schema no longer matches
                                the catalog (e.g. a new order_status value)

Values are never recorded for personal or secret columns, and tables marked
`ai_access: never` are only counted.
"""

import hashlib
import json
import sys
from datetime import datetime

import db
from ai import metadata

MAX_TRACKED_VALUES = 30  # columns with more distinct values than this are not value-profiled

DDL = [
    """
    CREATE TABLE IF NOT EXISTS meta_tables (
        table_name      VARCHAR(64) PRIMARY KEY,
        description     TEXT NOT NULL,
        grain           VARCHAR(255) NOT NULL,
        primary_key     JSON NOT NULL,
        relationships   JSON NULL,
        ownership       JSON NULL,
        access          JSON NOT NULL,
        ai_access       VARCHAR(16) NULL,
        notes           TEXT NULL,
        catalog_version CHAR(12) NOT NULL,
        synced_at       DATETIME NOT NULL
    ) ENGINE=InnoDB
    """,
    """
    CREATE TABLE IF NOT EXISTS meta_columns (
        table_name      VARCHAR(64) NOT NULL,
        column_name     VARCHAR(64) NOT NULL,
        position        INT NOT NULL,
        data_type       VARCHAR(64) NULL,
        description     TEXT NOT NULL,
        sensitivity     VARCHAR(16) NOT NULL,
        hidden_from     JSON NULL,
        allowed_values  JSON NULL,
        example         VARCHAR(255) NULL,
        catalog_version CHAR(12) NOT NULL,
        synced_at       DATETIME NOT NULL,
        PRIMARY KEY (table_name, column_name),
        CONSTRAINT fk_meta_columns_table FOREIGN KEY (table_name) REFERENCES meta_tables (table_name) ON DELETE CASCADE
    ) ENGINE=InnoDB
    """,
    """
    CREATE TABLE IF NOT EXISTS meta_column_stats (
        table_name     VARCHAR(64) NOT NULL,
        column_name    VARCHAR(64) NOT NULL,
        row_count      BIGINT NOT NULL,
        null_count     BIGINT NOT NULL,
        distinct_count BIGINT NULL,
        min_value      VARCHAR(64) NULL,
        max_value      VARCHAR(64) NULL,
        top_values     JSON NULL,
        profiled_at    DATETIME NOT NULL,
        PRIMARY KEY (table_name, column_name)
    ) ENGINE=InnoDB
    """,
    """
    CREATE TABLE IF NOT EXISTS meta_drift (
        drift_id     INT AUTO_INCREMENT PRIMARY KEY,
        kind         VARCHAR(32) NOT NULL,
        table_name   VARCHAR(64) NOT NULL,
        column_name  VARCHAR(64) NOT NULL DEFAULT '',
        detail       VARCHAR(255) NOT NULL,
        status       VARCHAR(12) NOT NULL DEFAULT 'open',
        first_seen   DATETIME NOT NULL,
        last_seen    DATETIME NOT NULL,
        resolved_at  DATETIME NULL,
        UNIQUE KEY uq_meta_drift (kind, table_name, column_name, detail),
        INDEX idx_meta_drift_status (status, last_seen),
        CHECK (status IN ('open', 'resolved')),
        CHECK (kind IN ('new_value', 'undocumented_column', 'missing_column', 'new_table', 'missing_table'))
    ) ENGINE=InnoDB
    """,
]


def ensure_tables() -> None:
    for stmt in DDL:
        db.execute(stmt)


def catalog_version() -> str:
    raw = metadata.CATALOG_PATH.read_bytes()
    return hashlib.sha256(raw).hexdigest()[:12]


def _json(v) -> str | None:
    return None if v is None else json.dumps(v, default=str)


# ---- sync: YAML -> database ------------------------------------------------------


def sync() -> dict:
    """Replace meta_tables / meta_columns with the current YAML (atomically)."""
    ensure_tables()
    cat = metadata.load()
    version = catalog_version()
    now = datetime.now().replace(microsecond=0)
    types = {
        (r.t, r.c): r.ty
        for r in db.query_df(
            "SELECT table_name AS t, column_name AS c, column_type AS ty "
            "FROM information_schema.columns WHERE table_schema = DATABASE()"
        ).itertuples()
    }
    with db.transaction() as cur:
        cur.execute("DELETE FROM meta_columns")
        cur.execute("DELETE FROM meta_tables")
        for tname, t in cat["tables"].items():
            cur.execute(
                """
                INSERT INTO meta_tables (table_name, description, grain, primary_key, relationships,
                                         ownership, access, ai_access, notes, catalog_version, synced_at)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                """,
                (tname, " ".join(t["description"].split()), t["grain"], _json(t["primary_key"]),
                 _json(t.get("relationships")), _json(t.get("ownership")), _json(t["access"]),
                 t.get("ai_access"), t.get("notes"), version, now),
            )
            cur.executemany(
                """
                INSERT INTO meta_columns (table_name, column_name, position, data_type, description,
                                          sensitivity, hidden_from, allowed_values, example,
                                          catalog_version, synced_at)
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                """,
                [
                    (tname, cname, i, types.get((tname, cname)), c["description"], c["sensitivity"],
                     _json(c.get("hidden_from")), _json(c.get("allowed_values")),
                     None if c.get("example") is None else str(c["example"]), version, now)
                    for i, (cname, c) in enumerate(t["columns"].items(), 1)
                ],
            )
    n_cols = sum(len(t["columns"]) for t in cat["tables"].values())
    return {"tables": len(cat["tables"]), "columns": n_cols, "version": version}


# ---- profile: live facts + drift ---------------------------------------------------


def _profile_table(table: str, columns: list[str], types: dict, values_allowed: set[str]) -> list[dict]:
    """One pass of aggregate counts, then value lists for low-cardinality columns."""
    q = lambda c: f"`{c}`"  # noqa: E731 (column names come from information_schema, not users)
    parts = ["COUNT(*) AS n"]
    for i, c in enumerate(columns):
        parts.append(f"COUNT({q(c)}) AS nn{i}")
        if not types[c].startswith(("json", "text", "blob", "longtext")):
            parts.append(f"COUNT(DISTINCT {q(c)}) AS d{i}")
        if c in values_allowed and types[c].startswith(("int", "tinyint", "bigint", "decimal", "double", "float", "date", "datetime")):
            parts.append(f"MIN({q(c)}) AS mn{i}, MAX({q(c)}) AS mx{i}")
    agg = db.query_one(f"SELECT {', '.join(parts)} FROM `{table}`")
    out = []
    for i, c in enumerate(columns):
        distinct = agg.get(f"d{i}")
        row = {
            "column": c, "row_count": agg["n"], "null_count": agg["n"] - agg[f"nn{i}"],
            "distinct_count": distinct,
            "min_value": None if agg.get(f"mn{i}") is None else str(agg[f"mn{i}"]),
            "max_value": None if agg.get(f"mx{i}") is None else str(agg[f"mx{i}"]),
            "top_values": None,
        }
        if c in values_allowed and distinct is not None and 0 < distinct <= MAX_TRACKED_VALUES:
            vals = db.query_df(
                f"SELECT {q(c)} AS v, COUNT(*) AS n FROM `{table}` WHERE {q(c)} IS NOT NULL "
                f"GROUP BY {q(c)} ORDER BY n DESC"
            )
            row["top_values"] = {str(v): int(n) for v, n in zip(vals.v, vals.n)}
        out.append(row)
    return out


def profile() -> dict:
    """Refresh meta_column_stats and record drift between the data and the catalog."""
    ensure_tables()
    cat = metadata.load()
    live = metadata.live_schema()
    types = {
        (r.t, r.c): r.ty
        for r in db.query_df(
            "SELECT table_name AS t, column_name AS c, column_type AS ty "
            "FROM information_schema.columns WHERE table_schema = DATABASE()"
        ).itertuples()
    }
    now = datetime.now().replace(microsecond=0)
    drift: list[tuple[str, str, str, str]] = []  # (kind, table, column, detail)

    # Schema drift.
    for tname, cols in live.items():
        if tname not in cat["tables"]:
            drift.append(("new_table", tname, "", "table exists in the database but not in the catalog"))
            continue
        documented = cat["tables"][tname]["columns"]
        for c in cols:
            if c not in documented:
                drift.append(("undocumented_column", tname, c, "column has no catalog entry"))
        for c in documented:
            if c not in cols:
                drift.append(("missing_column", tname, c, "column in the catalog no longer exists"))
    for tname in cat["tables"]:
        if tname not in live:
            drift.append(("missing_table", tname, "", "table in the catalog no longer exists"))

    # Data facts.
    stats_rows = []
    for tname, t in cat["tables"].items():
        if tname not in live:
            continue
        cols = [c for c in live[tname] if c in t["columns"]]
        never = t.get("ai_access") == "never"
        # Values/ranges only for non-personal, non-secret columns of tables the AI may use.
        value_ok = set() if never else {
            c for c in cols if t["columns"][c]["sensitivity"] in ("public", "internal")
        }
        typemap = {c: types[(tname, c)] for c in cols}
        for r in _profile_table(tname, cols, typemap, value_ok):
            stats_rows.append((tname, r))
            allowed = t["columns"][r["column"]].get("allowed_values")
            if allowed and r["top_values"]:
                documented = {str(k) for k in allowed}
                for value in r["top_values"]:
                    if value not in documented:
                        drift.append(("new_value", tname, r["column"],
                                      f"value '{value}' ({r['top_values'][value]} rows) is not described in the catalog"))

    with db.transaction() as cur:
        cur.execute("DELETE FROM meta_column_stats")
        cur.executemany(
            """
            INSERT INTO meta_column_stats (table_name, column_name, row_count, null_count, distinct_count,
                                           min_value, max_value, top_values, profiled_at)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)
            """,
            [(t, r["column"], r["row_count"], r["null_count"], r["distinct_count"], r["min_value"],
              r["max_value"], _json(r["top_values"]), now) for t, r in stats_rows],
        )
        # Upsert current drift; anything open that wasn't seen this run is resolved.
        for kind, tname, col, detail in drift:
            cur.execute(
                """
                INSERT INTO meta_drift (kind, table_name, column_name, detail, status, first_seen, last_seen)
                VALUES (%s, %s, %s, %s, 'open', %s, %s)
                ON DUPLICATE KEY UPDATE status = 'open', last_seen = VALUES(last_seen), resolved_at = NULL
                """,
                (kind, tname, col, detail[:255], now, now),
            )
        cur.execute(
            "UPDATE meta_drift SET status = 'resolved', resolved_at = %s WHERE status = 'open' AND last_seen < %s",
            (now, now),
        )
    return {"columns_profiled": len(stats_rows), "open_drift": len(drift)}


def open_drift() -> list[dict]:
    ensure_tables()
    return db.query_df(
        "SELECT kind, table_name, column_name, detail, first_seen, last_seen FROM meta_drift "
        "WHERE status = 'open' ORDER BY first_seen"
    ).to_dict("records")


def live_values(table: str, column: str) -> dict[str, int] | None:
    """Values currently present in a column (from the last profile), or None."""
    try:
        row = db.query_one(
            "SELECT top_values FROM meta_column_stats WHERE table_name = %s AND column_name = %s",
            (table, column),
        )
    except Exception:  # tables not created yet
        return None
    if not row or not row["top_values"]:
        return None
    return json.loads(row["top_values"]) if isinstance(row["top_values"], str) else row["top_values"]


if __name__ == "__main__":
    command = sys.argv[1] if len(sys.argv) > 1 else "sync"
    if command == "sync":
        ensure_tables()
        problems = metadata.validate(metadata.live_schema())
        if problems:
            print("catalog does not match the database; fix ai/metadata.yaml first:")
            for p in problems:
                print(f"  - {p}")
            sys.exit(1)
        r = sync()
        print(f"synced catalog {r['version']}: {r['tables']} tables, {r['columns']} columns")
    elif command == "profile":
        r = profile()
        print(f"profiled {r['columns_profiled']} columns; open drift alerts: {r['open_drift']}")
        for d in open_drift():
            print(f"  [{d['kind']}] {d['table_name']}.{d['column_name']}: {d['detail']}")
    elif command == "drift":
        rows = open_drift()
        print(f"{len(rows)} open drift alert(s)")
        for d in rows:
            print(f"  [{d['kind']}] {d['table_name']}.{d['column_name']}: {d['detail']} (since {d['first_seen']})")
    else:
        print(__doc__)
        sys.exit(2)
